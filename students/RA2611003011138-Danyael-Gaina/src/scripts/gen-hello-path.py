"""
Generates src/web/components/onboarding/helloPath.ts: the outline of "Hello" in Inter SemiBold
with overlapping contours merged, for the onboarding greeting's traced-ink animation.

Inter's glyphs (both the variable and static builds) keep overlapping contours, e.g. the crossbar
of "e" runs inside its bowl. Filled text hides that, but tracing the outline shows a stray line, so
the English greeting is drawn from this cleaned path instead of <text>.

Run from the repo root: python scripts/gen-hello-path.py   (needs fontTools and skia-pathops)
"""
from pathlib import Path

import pathops
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

WORD = 'Hello'
FONT = Path('node_modules/@fontsource/inter/files/inter-latin-600-normal.woff')
OUT = Path('src/web/components/onboarding/helloPath.ts')

font = TTFont(str(FONT))
upm = font['head'].unitsPerEm
cmap = font.getBestCmap()
glyphs = font.getGlyphSet()
hmtx = font['hmtx']

merged = pathops.Path()
x = 0
for ch in WORD:
    name = cmap[ord(ch)]
    glyph = pathops.Path()
    # Font units are y-up; SVG is y-down. Shift each glyph by the advance so far.
    glyphs[name].draw(TransformPen(glyph.getPen(), (1, 0, 0, -1, x, 0)))
    glyph.simplify(fix_winding=True)  # merges the glyph's overlapping contours
    merged = pathops.op(merged, glyph, pathops.PathOp.UNION)
    x += hmtx[name][0]

pen = SVGPathPen(None, ntos=lambda v: f'{v:.0f}')
merged.draw(pen)
d = pen.getCommands()

x_min, y_min, x_max, y_max = merged.bounds
# Same box the <text> greetings use: 1.5em tall, glyphs centred, so all three render at one size.
height = 1.5 * upm
y_top = (y_min + y_max) / 2 - height / 2
view_box = f'{x_min - 8:.0f} {y_top:.0f} {x_max - x_min + 16:.0f} {height:.0f}'

OUT.write_text(
    '// Generated by scripts/gen-hello-path.py; do not edit by hand.\n'
    '/** "Hello" in Inter SemiBold with overlapping contours merged, for the traced-ink greeting. */\n'
    f"export const HELLO_PATH = '{d}';\n"
    f"export const HELLO_VIEWBOX = '{view_box}';\n",
    encoding='utf-8',
    newline='\n',
)
print(f'wrote {OUT} ({len(d)} chars, viewBox {view_box})')
